"""Generate src/tables.rs from this Python (the behaviour xsession 2.3.0 has): str.casefold,
str.isspace, and str.isprintable (for repr())."""
import json
import sys
import unicodedata
from pathlib import Path

fold, space, nonprint = [], [], []
for cp in range(sys.maxunicode + 1):
    ch = chr(cp)
    if not ch.isprintable():
        if nonprint and nonprint[-1][1] == cp - 1:
            nonprint[-1][1] = cp
        else:
            nonprint.append([cp, cp])
    if 0xD800 <= cp <= 0xDFFF:
        continue
    if ch.casefold() != ch:
        fold.append((cp, ch.casefold()))
    if ch.isspace():
        space.append(cp)


def rust_str(text):
    return '"' + ''.join('\\u{%x}' % ord(c) for c in text) + '"'


out = ['// Generated by tools/gen_tables.py from Python %s (Unicode %s). Do not edit.'
       % (sys.version.split()[0], unicodedata.unidata_version),
       '',
       '/// Every code point whose `str.casefold()` differs from itself, sorted.',
       'pub static FOLD: &[(u32, &str)] = &[']
out += ['    (0x%x, %s),' % (cp, rust_str(f)) for cp, f in fold]
out += ['];', '', '/// Every code point for which `str.isspace()` is true, sorted.', 'pub static SPACE: &[u32] = &[']
out += ['    0x%x,' % cp for cp in space]
out += ['];', '', '/// Inclusive ranges of code points for which `str.isprintable()` is false, sorted.',
        'pub static NONPRINT: &[(u32, u32)] = &[']
out += ['    (0x%x, 0x%x),' % (a, b) for a, b in nonprint]
out += ['];', '', '/// cp437 decoding of bytes 0x80..=0xFF (zip names without the UTF-8 flag).',
        'pub static CP437_HIGH: [char; 128] = [']
out += ["    '\\u{%x}'," % ord(bytes([b]).decode('cp437')) for b in range(0x80, 0x100)]
out += ['];', '']
target = Path(__file__).resolve().parent.parent / 'src' / 'tables.rs'
target.parent.mkdir(exist_ok=True)
target.write_text('\n'.join(out), encoding='utf-8')
print(len(fold), 'fold entries;', len(space), 'space entries;', len(nonprint), 'non-printable ranges; Unicode',
      unicodedata.unidata_version)

# --- Codecs for XML declarations expat does not know (pyexpat's unknown-encoding handler). ---
import codecs  # noqa: E402
import encodings  # noqa: E402
import encodings.aliases  # noqa: E402
import pkgutil  # noqa: E402

template = bytes(range(256))
maps, errors, modules = [], [], []
for m in sorted(pkgutil.iter_modules(encodings.__path__), key=lambda m: m.name):
    try:
        info = codecs.lookup(m.name)
    except LookupError:
        continue
    if not getattr(info, '_is_text_encoding', True):
        modules.append((m.name, -2))
        continue
    try:
        decoded = template.decode(m.name, 'replace')
    except Exception as exc:
        errors.append((type(exc).__name__, str(exc)))
        modules.append((m.name, -10 - (len(errors) - 1)))
        continue
    if len(decoded) != 256:
        modules.append((m.name, -1))
        continue
    table = [ord(c) if c != '�' else -1 for c in decoded]
    if table not in maps:
        maps.append(table)
    modules.append((m.name, maps.index(table)))
aliases = sorted(encodings.aliases.aliases.items())
lines = ['', '/// encodings.aliases.aliases: normalised alias -> module.', 'pub static CODEC_ALIASES: &[(&str, &str)] = &[']
lines += ['    (%s, %s),' % (json.dumps(a), json.dumps(b)) for a, b in aliases]
lines += ['];', '', '/// Codec modules: >= 0 map index, -1 multi-byte, -2 not a text encoding, <= -10 decode error.',
          'pub static CODEC_MODULES: &[(&str, i32)] = &[']
lines += ['    (%s, %d),' % (json.dumps(n), v) for n, v in modules]
lines += ['];', '', '/// Byte -> code point maps of single-byte codecs (-1: undefined).', 'pub static CODEC_MAPS: &[[i32; 256]] = &[']
lines += ['    [%s],' % ', '.join(str(x) for x in t) for t in maps]
lines += ['];', '', '/// Exceptions raised when decoding the 256-byte template.', 'pub static CODEC_ERRORS: &[(&str, &str)] = &[']
lines += ['    (%s, %s),' % (json.dumps(c), json.dumps(m)) for c, m in errors]
lines += ['];', '']
with target.open('a', encoding='utf-8') as f:
    f.write('\n'.join(lines))
print(len(aliases), 'aliases;', len(modules), 'codec modules;', len(maps), 'maps;', len(errors), 'decode errors')
